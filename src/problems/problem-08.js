/**
 * Problem 08: multiplyTestRuns
 * Category: Operators
 *
 * Return total executions from runs per suite × number of suites.
 * Examples: 5, 4 → 20
 * Practice focus: binary *
 *
 * Timebox: 20 minutes or less.
 */
export function multiplyTestRuns(runsPerSuite, suiteCount) {
  return (runsPerSuite * suiteCount);
}
