/**
 * Problem 01: isString
 * Category: Primitive Types
 *
 * Return true when the supplied value is a JavaScript string.
 * Examples: 'ready' → true; 42 → false
 * Practice focus: typeof
 *
 * Timebox: 20 minutes or less.
 */
export function isString(value) {
  return typeof value === 'string';
}
