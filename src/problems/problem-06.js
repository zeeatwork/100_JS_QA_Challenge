/**
 * Problem 06: addRetryCounts
 * Category: Operators
 *
 * Return the sum of failed retries and manual retries.
 * Examples: 2, 3 → 5
 * Practice focus: binary +
 *
 * Timebox: 20 minutes or less.
 */
export function addRetryCounts(failedRetries, manualRetries) {
  return (failedRetries + manualRetries);
}
