/**
 * Problem 07: subtractOpenBugs
 * Category: Operators
 *
 * Return the number of bugs remaining after resolved bugs are removed.
 * Examples: 10, 4 → 6
 * Practice focus: binary -
 *
 * Timebox: 20 minutes or less.
 */
export function subtractOpenBugs(openBugs, resolvedBugs) {
  return (openBugs - resolvedBugs);
}
